-- =====================================================================================================================
-- Flotix demo data
-- ---------------------------------------------------------------------------------------------------------------------
-- PL/pgSQL functions that give an account a ready-to-present fleet with about 90 days (3 months) of history that ends
-- at the moment the function runs: vehicles, IoT devices, fuel records, GPS telemetry, maintenance requests (every
-- status), incidents, alerts, notifications, IoT orders and reports.
--
--   public.flotix_demo_owner_id(user_id)            -> owner UUID of an IAM user (users.id is an integer, the business
--                                                      tables reference owners by UUID)
--   public.flotix_seed_demo_data(user_id [, days])  -> generates the demo data of one account (idempotent)
--   public.flotix_seed_demo_data_for_all_users()    -> generates it for every account that does not have it yet
--   public.flotix_clear_demo_data(user_id)          -> removes the demo data of one account
--
-- Every generated row is registered in public.demo_data_rows, so clearing it never touches real data.
-- Installed by the AddDemoDataFunctions migration. The script is idempotent (CREATE OR REPLACE / IF NOT EXISTS).
-- =====================================================================================================================

CREATE TABLE IF NOT EXISTS public.demo_data_rows
(
    user_id    integer                  NOT NULL,
    table_name text                     NOT NULL,
    row_id     uuid                     NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT p_k_demo_data_rows PRIMARY KEY (table_name, row_id)
    );

CREATE INDEX IF NOT EXISTS i_x_demo_data_rows_user_id ON public.demo_data_rows (user_id);

COMMENT ON TABLE public.demo_data_rows IS 'Rows generated by flotix_seed_demo_data, used by flotix_clear_demo_data.';

-- ---------------------------------------------------------------------------------------------------------------------
-- Deterministic identifiers
-- ---------------------------------------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.flotix_demo_owner_id(p_user_id integer)
    RETURNS uuid
    LANGUAGE sql
    IMMUTABLE
    STRICT
AS
$$
SELECT md5('flotix:owner:' || p_user_id)::uuid;
$$;

COMMENT ON FUNCTION public.flotix_demo_owner_id(integer) IS
    'Owner UUID of an IAM user: md5(''flotix:owner:'' || users.id). Mirrored by DemoDataOwner.ForUser in the API.';

CREATE OR REPLACE FUNCTION public.flotix_demo_person_id(p_user_id integer, p_role text, p_index integer)
    RETURNS uuid
    LANGUAGE sql
    IMMUTABLE
    STRICT
AS
$$
SELECT md5('flotix:' || p_role || ':' || p_user_id || ':' || p_index)::uuid;
$$;

-- ---------------------------------------------------------------------------------------------------------------------
-- Seed one account
-- ---------------------------------------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.flotix_seed_demo_data(p_user_id integer, p_days integer DEFAULT 90)
    RETURNS integer
    LANGUAGE plpgsql
AS
$$
DECLARE
v_owner      uuid        := public.flotix_demo_owner_id(p_user_id);
    v_now        timestamptz := now();
    v_days       integer     := greatest(coalesce(p_days, 90), 14);
    v_start      timestamptz;

    -- Fleet profile (one entry per vehicle)
    v_types      text[]      := ARRAY ['Camión de carga', 'Camioneta', 'Mototaxi', 'Van de pasajeros',
                                       'Automóvil', 'Camión de carga', 'Camioneta', 'Automóvil'];
    v_statuses   text[]      := ARRAY ['Available', 'Available', 'Available', 'Available',
                                       'Available', 'InMaintenance', 'Available', 'Inactive'];
    v_liters     numeric[]   := ARRAY [58, 42, 9, 52, 38, 60, 44, 36];          -- average liters per refill
    v_km_per_day numeric[]   := ARRAY [175, 120, 65, 150, 85, 160, 110, 70];    -- average kilometers per day
    v_refill_gap numeric[]   := ARRAY [4, 4, 2.5, 4, 5, 4, 4.5, 5];             -- average days between refills
    v_vehicles   uuid[]      := '{}';
    v_drivers    uuid[]      := '{}';
    v_plates     text[]      := '{}';
    v_devices    uuid[]      := '{}';

    v_mechanics  uuid[];
    v_id         uuid;
    v_alert_id   uuid;
    v_row_id     uuid;
    v_driver     uuid;
    v_plate      text;
    v_km         numeric;
    v_liters_now numeric;
    v_at         timestamptz;
    v_end        timestamptz;
    v_status     text;
    v_cost       numeric;
    v_text       text;
    v_from       date;
    v_to         date;
    v_month      timestamptz;
    i            integer;
    k            integer;
    v_rows       integer;
BEGIN
    IF p_user_id IS NULL OR NOT EXISTS (SELECT 1 FROM public.users WHERE id = p_user_id) THEN
        RETURN 0;
END IF;

    -- Serializes concurrent calls for the same account (sign-up retry + backfill).
    PERFORM pg_advisory_xact_lock(hashtext('flotix_demo_data'), p_user_id);

    IF EXISTS (SELECT 1 FROM public.demo_data_rows WHERE user_id = p_user_id) THEN
        RETURN 0;
END IF;

    v_start := date_trunc('hour', v_now - make_interval(days => v_days));
    v_mechanics := ARRAY [public.flotix_demo_person_id(p_user_id, 'mechanic', 1),
                          public.flotix_demo_person_id(p_user_id, 'mechanic', 2),
                          public.flotix_demo_person_id(p_user_id, 'mechanic', 3)];

    -- ── Fleet: vehicles and fuel records ──────────────────────────────────────────────────────────────────────────
FOR i IN 1 .. array_length(v_types, 1)
        LOOP
            v_plate := 'FX' || p_user_id || '-' || lpad(i::text, 2, '0');
            v_driver := CASE WHEN i <= 6 THEN public.flotix_demo_person_id(p_user_id, 'driver', i) END;
            v_km := 12000 + i * 6850 + round((random() * 4000)::numeric, 0);
            v_at := v_start - make_interval(days => 20 + i * 3);

INSERT INTO fleet.vehicles (id, owner_id, driver_id, license_plate, vehicle_type, current_mileage, status,
                            created_at, updated_at)
VALUES (gen_random_uuid(), v_owner, v_driver, v_plate, v_types[i], v_km, 'Available', v_at, v_at)
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id) VALUES (p_user_id, 'fleet.vehicles', v_id);

v_vehicles := v_vehicles || v_id;
            v_drivers := v_drivers || coalesce(v_driver, public.flotix_demo_person_id(p_user_id, 'driver', 7));
            v_plates := v_plates || v_plate;

            -- Inactive vehicles stopped working a month into the period; the one in the workshop, six days ago.
            v_end := CASE v_statuses[i]
                         WHEN 'Inactive' THEN v_start + interval '30 days'
                         WHEN 'InMaintenance' THEN v_now - interval '6 days'
                         ELSE v_now - interval '2 hours' END;
            v_at := v_start + make_interval(hours => 7 + i * 5);

            WHILE v_at < v_end
                LOOP
                    v_liters_now := round(v_liters[i] * (0.82 + random() * 0.3)::numeric, 2);
INSERT INTO fuel.fuel_records (id, vehicle_id, driver_id, liters, cost, mileage_at_refill,
                               recorded_date, created_at, updated_at)
VALUES (gen_random_uuid(), v_id, v_drivers[i], v_liters_now,
        round(v_liters_now * (6.15 + random() * 0.6)::numeric, 2), round(v_km, 0), v_at, v_at, v_at)
    RETURNING id INTO v_row_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'fuel.fuel_records', v_row_id);

k := greatest(1, round(v_refill_gap[i] * (0.7 + random() * 0.6))::integer);
                    v_km := v_km + v_km_per_day[i] * k * (0.85 + random() * 0.3)::numeric;
                    v_at := v_at + make_interval(days => k, hours => (random() * 6)::integer - 3);
END LOOP;

UPDATE fleet.vehicles
SET current_mileage = round(v_km, 0),
    status          = v_statuses[i],
    updated_at      = least(v_end, v_now)
WHERE id = v_id;
END LOOP;

    -- ── Monitoring: IoT devices and GPS telemetry (every 6 hours + live readings of the last 3 hours) ─────────────
FOR i IN 1 .. array_length(v_vehicles, 1)
        LOOP
            CONTINUE WHEN v_statuses[i] = 'Inactive';
            v_at := v_start + make_interval(days => 1, hours => i);

INSERT INTO monitoring.iot_devices (id, vehicle_id, serial_number, is_connected, created_at, updated_at)
VALUES (gen_random_uuid(), v_vehicles[i], 'FLX-DEMO-' || p_user_id || '-' || lpad(i::text, 2, '0'),
        v_statuses[i] <> 'InMaintenance', v_at,
        CASE WHEN v_statuses[i] = 'InMaintenance' THEN v_now - interval '6 days' ELSE v_at END)
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'monitoring.iot_devices', v_id);
v_devices := v_devices || v_id;

            v_end := CASE WHEN v_statuses[i] = 'InMaintenance' THEN v_now - interval '6 days' ELSE v_now END;

WITH readings AS (SELECT ts
                  FROM generate_series(v_at, v_end - interval '3 hours', interval '6 hours') AS ts
                  UNION ALL
                  SELECT ts
                  FROM generate_series(v_end - interval '3 hours', v_end, interval '10 minutes') AS ts
                  WHERE v_statuses[i] <> 'InMaintenance'),
     inserted AS (
INSERT INTO monitoring.telemetry_data (id, device_id, latitude, longitude, speed, recorded_at,
                                       created_at, updated_at)
SELECT gen_random_uuid(),
       v_id,
       round((-12.0464 + (i - 4) * 0.018 +
              0.035 * sin(extract(epoch FROM ts) / 18000.0 + i))::numeric, 6),
       round((-77.0428 + (i - 4) * 0.012 +
              0.040 * cos(extract(epoch FROM ts) / 25200.0 + i))::numeric, 6),
       CASE
           WHEN extract(hour FROM ts AT TIME ZONE 'America/Lima') BETWEEN 6 AND 21
               THEN round((12 + random() * 58)::numeric, 1)
           ELSE 0 END,
       ts,
       ts,
       ts
FROM readings
         RETURNING id)
INSERT
INTO public.demo_data_rows (user_id, table_name, row_id)
SELECT p_user_id, 'monitoring.telemetry_data', id
FROM inserted;
END LOOP;

    -- ── Maintenance requests (every status; older ones are closed, recent ones are open) ──────────────────────────
FOR k IN 1 .. 14
        LOOP
            i := ((k * 3) % 7) + 1; -- vehicles 1..7, spread
            v_at := v_start + make_interval(days => (k - 1) * v_days / 14 + 2, hours => 9 + k % 8);
            v_status := CASE
                            WHEN k IN (3, 8) THEN 'Rejected'
                            WHEN k <= 10 THEN 'Completed'
                            WHEN k = 11 THEN 'Approved'
                            WHEN k = 12 THEN 'Quoted'
                            ELSE 'Pending' END;
            v_text := (ARRAY ['Cambio de aceite y filtros (mantenimiento preventivo)',
                'Ruido en la suspensión delantera',
                'Revisión del sistema de frenos',
                'Cambio de pastillas de freno',
                'Falla en el sistema eléctrico: luces intermitentes',
                'Alineamiento y balanceo',
                'Cambio de batería',
                'Revisión del sistema de refrigeración: temperatura alta',
                'Cambio de llantas traseras',
                'Mantenimiento preventivo de 50 000 km',
                'Fuga de aceite en el motor',
                'Revisión de la caja de cambios',
                'Luz de check engine encendida',
                'Cambio de correa de distribución'])[k];
            v_cost := CASE WHEN v_status = 'Pending' THEN 0 ELSE round((180 + random() * 2300)::numeric, 2) END;

INSERT INTO maintenance.maintenance_requests (id, vehicle_id, mechanic_id, description, estimated_cost,
                                              status, request_date, created_at, updated_at)
VALUES (gen_random_uuid(), v_vehicles[i], v_mechanics[1 + k % 3], v_text, v_cost, v_status, v_at, v_at,
        least(v_now, v_at + make_interval(days => CASE WHEN v_status = 'Pending' THEN 0 ELSE 1 + k % 4 END)))
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'maintenance.maintenance_requests', v_id);

IF v_status IN ('Quoted', 'Completed') THEN
                INSERT INTO notifications.notifications (id, user_id, alert_id, message, is_read, sent_date,
                                                         created_at, updated_at)
                VALUES (gen_random_uuid(), v_owner, NULL,
                        CASE v_status
                            WHEN 'Quoted' THEN 'El taller envió el presupuesto de ' || v_plates[i] || ': S/ ' || v_cost
                            ELSE 'El mantenimiento de ' || v_plates[i] || ' fue completado.' END,
                        v_at < v_now - interval '7 days', v_at + interval '1 day', v_at + interval '1 day',
                        v_at + interval '1 day')
                RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'notifications.notifications', v_id);
END IF;
END LOOP;

    -- The vehicle in the workshop has its repair in progress.
    v_at := v_now - interval '6 days';
INSERT INTO maintenance.maintenance_requests (id, vehicle_id, mechanic_id, description, estimated_cost, status,
                                              request_date, created_at, updated_at)
VALUES (gen_random_uuid(), v_vehicles[6], v_mechanics[1], 'Reparación del embrague', 1450.00, 'InRepair', v_at,
        v_at, v_at + interval '2 days')
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'maintenance.maintenance_requests', v_id);

-- ── Incidents, each with its alert and owner notification ─────────────────────────────────────────────────────
FOR k IN 1 .. 10
        LOOP
            i := ((k * 5) % 7) + 1;
            v_at := v_start + make_interval(days => (k - 1) * v_days / 10 + 4, hours => 8 + (k * 3) % 11);
            v_status := CASE WHEN k <= 6 THEN 'Resolved' WHEN k <= 8 THEN 'InReview' ELSE 'Open' END;
            v_text := (ARRAY ['Llanta ponchada en la Panamericana Sur',
                'Choque leve en estacionamiento, raspón en la puerta',
                'Luz de check engine encendida en ruta',
                'Motor se apagó en semáforo',
                'Pérdida de presión en las llantas',
                'Parabrisas rajado por piedra',
                'Falla en el sistema de arranque',
                'Ruido extraño al frenar',
                'Retrovisor dañado',
                'Batería descargada al iniciar la ruta'])[k];

INSERT INTO incidents.incidents (id, vehicle_id, driver_id, description, status, reported_date, created_at,
                                 updated_at)
VALUES (gen_random_uuid(), v_vehicles[i], v_drivers[i], v_text, v_status, v_at, v_at,
        least(v_now, v_at + make_interval(days => CASE WHEN v_status = 'Open' THEN 0 ELSE 1 + k % 3 END)))
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id) VALUES (p_user_id, 'incidents.incidents', v_id);

INSERT INTO notifications.alerts (id, vehicle_id, alert_type, trigger_date, created_at, updated_at)
VALUES (gen_random_uuid(), v_vehicles[i], 'Incidente reportado', v_at, v_at, v_at)
    RETURNING id INTO v_alert_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'notifications.alerts', v_alert_id);

INSERT INTO notifications.notifications (id, user_id, alert_id, message, is_read, sent_date, created_at,
                                         updated_at)
VALUES (gen_random_uuid(), v_owner, v_alert_id, 'Incidente reportado en ' || v_plates[i] || ': ' || v_text,
        v_at < v_now - interval '7 days', v_at, v_at, v_at)
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'notifications.notifications', v_id);
END LOOP;

    -- ── Other alerts: speeding, upcoming maintenance, unusual fuel consumption, disconnected device ───────────────
FOR k IN 1 .. 12
        LOOP
            i := ((k * 2) % 7) + 1;
            v_at := v_start + make_interval(days => (k - 1) * v_days / 12 + 3, hours => 10 + k % 9);
            IF k = 12 THEN
                i := 6;
                v_at := v_now - interval '6 days';
END IF;
            v_text := CASE
                          WHEN k = 12 THEN 'Dispositivo IoT desconectado'
                          WHEN k % 4 = 1 THEN 'Exceso de velocidad (' || (85 + (k * 7) % 25) || ' km/h)'
                          WHEN k % 4 = 2 THEN 'Mantenimiento próximo (' || (85 + k % 10) || '% de kilometraje)'
                          WHEN k % 4 = 3 THEN 'Consumo de combustible inusual'
                          ELSE 'Exceso de velocidad (' || (90 + k % 20) || ' km/h)' END;

INSERT INTO notifications.alerts (id, vehicle_id, alert_type, trigger_date, created_at, updated_at)
VALUES (gen_random_uuid(), v_vehicles[i], v_text, v_at, v_at, v_at)
    RETURNING id INTO v_alert_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'notifications.alerts', v_alert_id);

INSERT INTO notifications.notifications (id, user_id, alert_id, message, is_read, sent_date, created_at,
                                         updated_at)
VALUES (gen_random_uuid(), v_owner, v_alert_id, v_text || ' en el vehículo ' || v_plates[i] || '.',
        v_at < v_now - interval '7 days', v_at, v_at, v_at)
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id)
VALUES (p_user_id, 'notifications.notifications', v_id);
END LOOP;

    -- ── Commerce: IoT orders ──────────────────────────────────────────────────────────────────────────────────────
FOR k IN 1 .. 5
        LOOP
            v_at := v_start + make_interval(days => (k - 1) * v_days / 5 + 1, hours => 11);
            v_status := (ARRAY ['Delivered', 'Delivered', 'Cancelled', 'Preparing', 'PendingPayment'])[k];
            i := (ARRAY [4, 3, 1, 2, 1])[k]; -- quantity

INSERT INTO commerce.iot_orders (id, owner_id, quantity, total_amount, status, order_date, created_at,
                                 updated_at)
VALUES (gen_random_uuid(), v_owner, i, i * 149.90, v_status, v_at, v_at,
        least(v_now, v_at + make_interval(days => CASE WHEN v_status = 'Delivered' THEN 5 ELSE 1 END)))
    RETURNING id INTO v_id;
INSERT INTO public.demo_data_rows (user_id, table_name, row_id) VALUES (p_user_id, 'commerce.iot_orders', v_id);
END LOOP;

    -- ── Analytics: monthly reports of the last two months + one for the whole period ──────────────────────────────
FOR k IN 0 .. 2
        LOOP
            IF k = 0 THEN
                v_from := v_start::date;
                v_to := v_now::date;
                v_at := v_now - interval '1 hour';
ELSE
                v_month := date_trunc('month', v_now) - make_interval(months => k);
                v_from := greatest(v_month::date, v_start::date);
                v_to := (v_month + interval '1 month' - interval '1 day')::date;
                v_at := v_month + interval '1 month' + interval '9 hours';
END IF;

WITH inserted AS (
INSERT INTO analytics.reports (id, owner_id, report_type, filter_params, generated_date, created_at,
                               updated_at)
-- Same JSON shape the API writes (Report.FilterParams): {"from":"yyyy-MM-dd","to":"yyyy-MM-dd"}
SELECT gen_random_uuid(), v_owner, rt,
       format('{"from":"%s","to":"%s"}', to_char(v_from, 'YYYY-MM-DD'), to_char(v_to, 'YYYY-MM-DD')),
       v_at, v_at, v_at
FROM unnest(ARRAY ['FuelConsumption', 'MaintenanceCost']) AS rt
    RETURNING id)
INSERT
INTO public.demo_data_rows (user_id, table_name, row_id)
SELECT p_user_id, 'analytics.reports', id
FROM inserted;
END LOOP;

SELECT count(*) INTO v_rows FROM public.demo_data_rows WHERE user_id = p_user_id;
RETURN v_rows;
END;
$$;

COMMENT ON FUNCTION public.flotix_seed_demo_data(integer, integer) IS
    'Generates the demo fleet of an IAM user with p_days (default 90) of history up to now(). Idempotent: returns 0 when the account already has demo data.';

-- ---------------------------------------------------------------------------------------------------------------------
-- Seed every account that does not have demo data yet (a failure in one account never stops the others)
-- ---------------------------------------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.flotix_seed_demo_data_for_all_users(p_days integer DEFAULT 90)
    RETURNS integer
    LANGUAGE plpgsql
AS
$$
DECLARE
v_user_id integer;
    v_seeded  integer := 0;
BEGIN
FOR v_user_id IN SELECT id FROM public.users ORDER BY id
    LOOP
BEGIN
                IF public.flotix_seed_demo_data(v_user_id, p_days) > 0 THEN
                    v_seeded := v_seeded + 1;
END IF;
EXCEPTION
                WHEN OTHERS THEN
                    RAISE WARNING 'Demo data could not be generated for user %: %', v_user_id, SQLERRM;
END;
END LOOP;
RETURN v_seeded;
END;
$$;

-- ---------------------------------------------------------------------------------------------------------------------
-- Clear one account. Rows that users attached to demo vehicles, devices or alerts are removed too, because the
-- foreign keys (ON DELETE RESTRICT) would otherwise prevent deleting them.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.flotix_clear_demo_data(p_user_id integer)
    RETURNS integer
    LANGUAGE plpgsql
AS
$$
DECLARE
v_vehicles uuid[];
    v_devices  uuid[];
    v_alerts   uuid[];
    v_rows     integer;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtext('flotix_demo_data'), p_user_id);

SELECT count(*) INTO v_rows FROM public.demo_data_rows WHERE user_id = p_user_id;
IF v_rows = 0 THEN
        RETURN 0;
END IF;

SELECT array_agg(row_id) INTO v_vehicles
FROM public.demo_data_rows WHERE user_id = p_user_id AND table_name = 'fleet.vehicles';
SELECT array_agg(row_id) INTO v_devices
FROM public.demo_data_rows WHERE user_id = p_user_id AND table_name = 'monitoring.iot_devices';
SELECT array_agg(row_id) INTO v_alerts
FROM public.demo_data_rows WHERE user_id = p_user_id AND table_name = 'notifications.alerts';

DELETE FROM notifications.notifications n
WHERE n.alert_id = ANY (coalesce(v_alerts, '{}'))
   OR n.id IN (SELECT row_id FROM public.demo_data_rows
               WHERE user_id = p_user_id AND table_name = 'notifications.notifications');
DELETE FROM notifications.alerts WHERE id = ANY (coalesce(v_alerts, '{}')) OR vehicle_id = ANY (coalesce(v_vehicles, '{}'));
DELETE FROM monitoring.telemetry_data WHERE device_id = ANY (coalesce(v_devices, '{}'));
DELETE FROM monitoring.iot_devices WHERE id = ANY (coalesce(v_devices, '{}')) OR vehicle_id = ANY (coalesce(v_vehicles, '{}'));
DELETE FROM fuel.fuel_records WHERE vehicle_id = ANY (coalesce(v_vehicles, '{}'));
DELETE FROM maintenance.maintenance_requests WHERE vehicle_id = ANY (coalesce(v_vehicles, '{}'));
DELETE FROM incidents.incidents WHERE vehicle_id = ANY (coalesce(v_vehicles, '{}'));
DELETE FROM commerce.iot_orders
WHERE id IN (SELECT row_id FROM public.demo_data_rows WHERE user_id = p_user_id AND table_name = 'commerce.iot_orders');
DELETE FROM analytics.reports
WHERE id IN (SELECT row_id FROM public.demo_data_rows WHERE user_id = p_user_id AND table_name = 'analytics.reports');
DELETE FROM fleet.vehicles WHERE id = ANY (coalesce(v_vehicles, '{}'));

DELETE FROM public.demo_data_rows WHERE user_id = p_user_id;
RETURN v_rows;
END;
$$;

COMMENT ON FUNCTION public.flotix_clear_demo_data(integer) IS
    'Removes the rows generated by flotix_seed_demo_data for an IAM user. Returns the number of registered demo rows.';